#!/usr/bin/env python3
"""Turns a profile picture into src/gh_avatar.h for the GitHub page.

    python tools/make_avatar.py picture.png            88 px, the page's size
    python tools/make_avatar.py picture.png --size 88

The picture is cropped to a centred square, scaled, and cut to a circle with a
black surround (the page background), then written as RGB565 words.

Needs Pillow:  pip install pillow
"""
import argparse
import sys

from PIL import Image, ImageDraw

OUT = "src/gh_avatar.h"


def rgb565(r, g, b):
    return ((r & 0xF8) << 8) | ((g & 0xFC) << 3) | (b >> 3)


def convert(path, size):
    """The picture as size*size RGB565 words, row by row."""
    im = Image.open(path).convert("RGBA")
    side = min(im.size)
    left, top = (im.width - side) // 2, (im.height - side) // 2
    im = im.crop((left, top, left + side, top + side)).resize((size, size), Image.LANCZOS)
    # Transparent pixels sit on black, like the page behind them.
    flat = Image.new("RGB", im.size, (0, 0, 0))
    flat.paste(im, mask=im.split()[3])
    # Draw the mask 4x larger and scale it down, for a smooth rim.
    big = Image.new("L", (size * 4, size * 4), 0)
    ImageDraw.Draw(big).ellipse((0, 0, size * 4 - 1, size * 4 - 1), fill=255)
    mask = big.resize((size, size), Image.LANCZOS)
    out = Image.composite(flat, Image.new("RGB", flat.size, (0, 0, 0)), mask)
    return [rgb565(*px) for px in out.getdata()]


def header(words, size):
    lines = [
        "#pragma once",
        "// Generated by tools/make_avatar.py. Do not edit; run the tool again.",
        "#include <stdint.h>",
        "#include <pgmspace.h>",
        "",
        f"static const int GH_AVATAR_SIZE = {size};",
        "static const uint16_t gh_avatar[] PROGMEM = {",
    ]
    for i in range(0, len(words), 12):
        lines.append("  " + ",".join(f"0x{w:04X}" for w in words[i:i + 12]) + ",")
    lines.append("};")
    return "\n".join(lines) + "\n"


def main(argv):
    p = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    p.add_argument("picture")
    p.add_argument("--size", type=int, default=88)
    a = p.parse_args(argv)
    if not 16 <= a.size <= 110:
        p.error("--size must be 16 to 110")
    words = convert(a.picture, a.size)
    assert len(words) == a.size * a.size
    with open(OUT, "w", encoding="ascii", newline="\n") as f:
        f.write(header(words, a.size))
    print(f"{OUT}: {a.size}x{a.size}, {len(words) * 2} bytes")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
